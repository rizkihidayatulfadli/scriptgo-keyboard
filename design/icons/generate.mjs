// Generates ScriptGoIcons.kt (Compose ImageVectors) and the keyboard-settings VectorDrawables
// (res/drawable, the "drawables" map: file name -> [Lucide icon, size in dp]) from Lucide icons
// listed in icons.json.
//
// Usage, from the repo root:
//   (cd /tmp && npm pack lucide-static@1.48.0 && tar xzf lucide-static-1.48.0.tgz)
//   node design/icons/generate.mjs /tmp/package/icon-nodes.json
// Lucide is ISC-licensed (design/icons/LICENSE-lucide.txt).
import { readFileSync, writeFileSync } from "node:fs";

const OUT = "android/app/src/main/java/com/magickeyboard/manager/ui/theme/ScriptGoIcons.kt";
const config = JSON.parse(readFileSync(new URL("icons.json", import.meta.url), "utf8"));
const nodes = JSON.parse(readFileSync(process.argv[2], "utf8"));

const n = (v) => Number(v ?? 0);
const circle = (cx, cy, rx, ry) => `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0z`;
function toPath([tag, a]) {
  switch (tag) {
    case "path": return a.d;
    case "circle": return circle(n(a.cx), n(a.cy), n(a.r), n(a.r));
    case "ellipse": return circle(n(a.cx), n(a.cy), n(a.rx), n(a.ry));
    case "line": return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case "polyline": case "polygon": {
      const p = a.points.trim().split(/[\s,]+/).map(Number);
      let d = `M${p[0]} ${p[1]}`;
      for (let i = 2; i < p.length; i += 2) d += `L${p[i]} ${p[i + 1]}`;
      return tag === "polygon" ? d + "z" : d;
    }
    case "rect": {
      const x = n(a.x), y = n(a.y), w = n(a.width), h = n(a.height);
      const rx = Math.min(n(a.rx ?? a.ry), w / 2), ry = Math.min(n(a.ry ?? a.rx), h / 2);
      if (!rx) return `M${x} ${y}h${w}v${h}h${-w}z`;
      return `M${x + rx} ${y}h${w - 2 * rx}a${rx} ${ry} 0 0 1 ${rx} ${ry}v${h - 2 * ry}a${rx} ${ry} 0 0 1 ${-rx} ${ry}` +
        `h${-(w - 2 * rx)}a${rx} ${ry} 0 0 1 ${-rx} ${-ry}v${-(h - 2 * ry)}a${rx} ${ry} 0 0 1 ${rx} ${-ry}z`;
    }
    default: throw new Error(`unsupported element <${tag}>`);
  }
}

const icons = Object.entries(config.icons).map(([name, lucide]) => {
  if (!nodes[lucide]) throw new Error(`unknown Lucide icon ${lucide}`);
  // One Compose path per SVG element: a path may start with a relative "m", so they can't be joined.
  const paths = nodes[lucide].map(toPath).map((d) => `"${d}"`).join(", ");
  return `    /** Lucide \`${lucide}\`. */\n    val ${name}: ImageVector by lazy { icon("${name}", ${paths}) }`;
});

writeFileSync(OUT, `// Generated by design/icons/generate.mjs from Lucide ${config.lucide} (ISC). Do not edit by hand;
// change design/icons/icons.json and run the generator.
package com.magickeyboard.manager.ui.theme

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

/** Lucide line icons (24 × 24, 2 px round strokes); \`Icon\` tints them with the content colour. */
object ScriptGoIcons {
${icons.join("\n\n")}

    private fun icon(name: String, vararg paths: String): ImageVector {
        val builder = ImageVector.Builder(name = name, defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = 24f, viewportHeight = 24f)
        for (pathData in paths) {
            builder.addPath(
                pathData = addPathNodes(pathData),
                fill = null,
                stroke = SolidColor(Color.Black),
                strokeLineWidth = 2f,
                strokeLineCap = StrokeCap.Round,
                strokeLineJoin = StrokeJoin.Round,
            )
        }
        return builder.build()
    }
}
`);
console.log(`${OUT}: ${icons.length} icons`);

// HeliBoard settings screens draw these with painterResource + Icon, which tints them; the colour
// only matters where a drawable is shown untinted.
const DRAWABLES = "android/app/src/main/res/drawable";
// Lucide sometimes packs arc flags ("a2 2 0 0022 17"); older Android path parsers need them spelled out.
const NUM = /^[\s,]*(-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?)/i;
const FLAG = /^[\s,]*([01])/;
function expandArcs(d) {
  return d.replace(/([aA])([^a-zA-Z]*)/g, (_, cmd, args) => {
    const out = [];
    let rest = args;
    while (rest.trim()) {
      for (const re of [NUM, NUM, NUM, FLAG, FLAG, NUM, NUM]) {
        const m = rest.match(re);
        if (!m) throw new Error(`bad arc arguments "${args}" in ${d}`);
        out.push(m[1]);
        rest = rest.slice(m[0].length);
      }
    }
    return `${cmd}${out.join(" ")}`;
  });
}
for (const [file, [lucide, size]] of Object.entries(config.drawables)) {
  if (!nodes[lucide]) throw new Error(`unknown Lucide icon ${lucide}`);
  const paths = nodes[lucide].map(toPath).map(expandArcs).map((d) => `    <path
        android:pathData="${d}"
        android:strokeColor="@color/foreground"
        android:strokeWidth="2"
        android:strokeLineCap="round"
        android:strokeLineJoin="round" />`).join("\n");
  writeFileSync(`${DRAWABLES}/${file}.xml`, `<?xml version="1.0" encoding="utf-8"?>
<!--
    Lucide \`${lucide}\` ${config.lucide}, generated by design/icons/generate.mjs. Do not edit by hand.
    SPDX-License-Identifier: ISC
-->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${size}dp"
    android:height="${size}dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
${paths}
</vector>
`);
}
console.log(`${DRAWABLES}: ${Object.keys(config.drawables).length} drawables`);
