// Generates the contact-field icon set from Phosphor Fill icons listed in field-icons.json:
//   engine/…/contacts/FieldIconCatalog.kt      names + keywords + type defaults (for FieldIcons.pick)
//   extension/src/engine/fieldIconCatalog.ts   the same, for the extension's port
//   android/…/ui/theme/FieldIconVectors.kt     Compose ImageVectors (filled, 256 × 256 viewport)
//   extension/src/fieldIconPaths.ts            SVG path data for the extension
//
// Usage, from the repo root:
//   (cd /tmp && npm pack @phosphor-icons/core@2.1.1 && tar xzf phosphor-icons-core-2.1.1.tgz)
//   node design/icons/generate-fields.mjs /tmp/package/assets/fill
// Phosphor is MIT-licensed (design/icons/LICENSE-phosphor.txt).
import { readFileSync, writeFileSync } from "node:fs";

const config = JSON.parse(readFileSync(new URL("field-icons.json", import.meta.url), "utf8"));
const dir = process.argv[2];
if (!dir) throw new Error("usage: node design/icons/generate-fields.mjs <phosphor>/assets/fill");

const names = [...new Set([...config.icons.map((i) => i.name), ...Object.values(config.typeDefaults)])];
const paths = Object.fromEntries(
  names.map((name) => {
    const svg = readFileSync(`${dir}/${name}-fill.svg`, "utf8");
    const elements = [...svg.matchAll(/<(\w+)[\s>]/g)].map((m) => m[1]).filter((t) => t !== "svg");
    if (elements.some((t) => t !== "path")) throw new Error(`${name}: only <path> is supported, found ${elements.join(", ")}`);
    return [name, [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1])];
  }),
);

for (const icon of config.icons) {
  for (const k of icon.keywords) {
    if (k !== k.toLowerCase().replace(/[^a-z0-9 ]/g, "").replace(/\s+/g, " ").trim()) throw new Error(`keyword "${k}" of ${icon.name} is not normalized`);
  }
}

const header = (comment) => `${comment} Generated by design/icons/generate-fields.mjs from design/icons/field-icons.json
${comment} (Phosphor ${config.phosphor}, MIT). Do not edit by hand.`;
const kstr = (s) => JSON.stringify(s);

writeFileSync(
  "engine/src/main/kotlin/com/magickeyboard/contacts/FieldIconCatalog.kt",
  `${header("//")}
package com.magickeyboard.contacts

/** Field icons in match order, each with the words that pick it; see [FieldIcons]. */
internal object FieldIconCatalog {
    val icons: List<Pair<String, List<String>>> = listOf(
${config.icons.map((i) => `        ${kstr(i.name)} to listOf(${i.keywords.map(kstr).join(", ")}),`).join("\n")}
    )

    /** Icon per field type key, when no keyword matches. */
    val typeDefaults: Map<String, String> = mapOf(
${Object.entries(config.typeDefaults).map(([t, n]) => `        ${kstr(t)} to ${kstr(n)},`).join("\n")}
    )

    /** Every icon a field may have, in gallery order. */
    val all: List<String> = listOf(
${names.map((n) => `        ${kstr(n)},`).join("\n")}
    )
}
`,
);

writeFileSync(
  "extension/src/engine/fieldIconCatalog.ts",
  `${header("//")}

/** Field icons in match order, each with the words that pick it; see fieldIcons.ts. */
export const FIELD_ICON_KEYWORDS: readonly (readonly [string, readonly string[]])[] = [
${config.icons.map((i) => `  [${kstr(i.name)}, [${i.keywords.map(kstr).join(", ")}]],`).join("\n")}
];

/** Icon per field type key, when no keyword matches. */
export const FIELD_ICON_TYPE_DEFAULTS: Readonly<Record<string, string>> = {
${Object.entries(config.typeDefaults).map(([t, n]) => `  ${kstr(t)}: ${kstr(n)},`).join("\n")}
};

/** Every icon a field may have, in gallery order. */
export const FIELD_ICON_NAMES: readonly string[] = [
${names.map((n) => `  ${kstr(n)},`).join("\n")}
];
`,
);

writeFileSync(
  "extension/src/fieldIconPaths.ts",
  `${header("//")}

/** SVG path data (viewBox 0 0 256 256, filled with currentColor) per field icon. */
export const FIELD_ICON_PATHS: Readonly<Record<string, readonly string[]>> = {
${names.map((n) => `  ${kstr(n)}: [${paths[n].map(kstr).join(", ")}],`).join("\n")}
};
`,
);

writeFileSync(
  "android/app/src/main/java/com/magickeyboard/manager/ui/theme/FieldIconVectors.kt",
  `${header("//")}
package com.magickeyboard.manager.ui.theme

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

/** Filled Phosphor icons for contact fields, by name (see com.magickeyboard.contacts.FieldIcons). */
object FieldIconVectors {
    private val cache = HashMap<String, ImageVector>()

    /** The icon called [name], or null for an unknown name. */
    operator fun get(name: String): ImageVector? {
        cache[name]?.let { return it }
        val paths = PATHS[name] ?: return null
        val builder = ImageVector.Builder(name = name, defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = 256f, viewportHeight = 256f)
        for (pathData in paths) builder.addPath(pathData = addPathNodes(pathData), fill = SolidColor(Color.Black))
        return builder.build().also { cache[name] = it }
    }

    private val PATHS: Map<String, Array<String>> = mapOf(
${names.map((n) => `        ${kstr(n)} to arrayOf(${paths[n].map(kstr).join(", ")}),`).join("\n")}
    )
}
`,
);
console.log(`${names.length} field icons (${config.icons.length} with keywords)`);
